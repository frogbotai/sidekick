import { GLOBAL_QUESTIONS, SITES } from './sites';
import { type LiveState, SITE_STEP_IDS, type Status, type Step, STEP_LABELS } from './state';

export const ICON: Record<Status, string> = {
  pending: '·',
  running: '▶',
  passed: '✅',
  failed: '❌',
  skipped: '⏭',
};

function cell(text: string) {
  return text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function duration(state: LiveState) {
  if (!state.startedAt || !state.finishedAt) return 'unfinished';

  return `${Math.max(1, Math.round((state.finishedAt - state.startedAt) / 60_000))} min`;
}

function stepTable(steps: Step[]) {
  return [
    '| Step | Result | Detail | ms |',
    '|---|---|---|---|',
    ...steps.map(
      (step) =>
        `| ${step.label} | ${ICON[step.status]} | ${cell(step.detail || '—')} | ${step.ms ?? '—'} |`,
    ),
  ];
}

/** Questions the owner answers for the sites that ran. */
export function questionsFor(state: LiveState) {
  const ran = new Set(
    state.sites.filter((site) => site.status !== 'skipped').map((site) => site.id),
  );

  return [
    ...GLOBAL_QUESTIONS,
    ...SITES.filter((site) => ran.has(site.id)).flatMap((site) => site.questions),
  ];
}

/** The report the owner pastes back: per-site tables, the run's steps, events and answers. */
export function toMarkdown(state: LiveState) {
  const date = new Date(state.startedAt ?? Date.now()).toISOString().slice(0, 10);
  const ran = state.sites.filter((site) => site.status !== 'skipped');
  const nameOf = (id: string) => SITES.find((site) => site.id === id)?.name ?? id;

  const out = [
    `## Live run (ticket 271, ${date})`,
    '',
    `Generated by the live runner extension. ${state.chrome}. Duration: ${duration(state)}. Sites: ${ran.map((site) => nameOf(site.id)).join(', ') || 'none'}.`,
    '',
    '### Results',
    '',
    `| Site | ${SITE_STEP_IDS.map((id) => STEP_LABELS[id]).join(' | ')} |`,
    `|---|${SITE_STEP_IDS.map(() => '---').join('|')}|`,
    ...state.sites.map((site) => {
      const icons = SITE_STEP_IDS.map((id) => {
        const step = site.steps.find((entry) => entry.id === id);

        return step ? ICON[step.status] : '—';
      });

      return `| ${nameOf(site.id)} | ${icons.join(' | ')} |`;
    }),
    '',
    '### Snapshot numbers',
    '',
    '| Site | Refs | ≈Tokens | ms | Frames with refs | Redacted | Refs kept | Page chars | Page truncated | Page frames with refs | Iframes | Not readable |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|',
    ...ran.flatMap(({ id, numbers: n }) =>
      n
        ? [
            `| ${nameOf(id)} | ${n.refs} | ${n.tokens} | ${n.ms} | ${n.frames} | ${n.redacted} | ${n.stable === undefined ? '—' : `${Math.round(n.stable * 100)}%`} | ${n.pageChars ?? '—'} | ${n.pageTruncated === undefined ? '—' : n.pageTruncated ? 'yes' : 'no'} | ${n.pageFrames ?? '—'} | ${n.iframes ?? '—'} | ${n.unreadable ?? '—'} |`,
          ]
        : [],
    ),
    '',
    '### Run',
    '',
    ...stepTable(state.run),
    '',
    '### Events',
    '',
    ...(state.events.length > 0 ? state.events.map((event) => `- ${event}`) : ['- none']),
    '',
    '### Details per site',
    '',
  ];

  for (const site of ran) {
    const info = SITES.find((entry) => entry.id === site.id);

    out.push(
      `#### ${nameOf(site.id)}`,
      '',
      `- URL: ${info?.url ?? '?'} (${info?.note ?? ''})`,
      `- Overall: ${ICON[site.status]}${site.reason ? ` ${site.reason}` : ''}`,
      '',
      ...stepTable(site.steps),
      '',
    );
  }

  out.push('### Owner answers', '');

  for (const question of questionsFor(state)) {
    out.push(`- ${question.text} **${state.answers[question.id] ?? 'not answered'}**`);
  }

  if (state.notes.trim()) out.push('', `Owner notes: ${state.notes.trim()}`);

  out.push(
    '',
    '<details><summary>Run log</summary>',
    '',
    '```',
    ...state.log.slice(-300),
    '```',
    '',
    '</details>',
  );

  return out.join('\n');
}
